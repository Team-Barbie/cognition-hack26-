"""`imports.register`: snapshot host-produced files and label them honestly. Never `runtime_captured`."""

from __future__ import annotations

import sqlite3
from datetime import UTC, datetime
from enum import StrEnum
from pathlib import Path
from typing import Literal

from ar.models import Record
from ar.snapshots import BlobStore, BrokerError, sha256_bytes

HOST_ASSURANCE = (
    "Host-reported: the runtime did not run this and did not enforce the original execution permissions. "
    "The file is a snapshot of what the host supplied; reproduce it through managed execution to obtain "
    "runtime-captured evidence."
)
DERIVED_ASSURANCE = (
    "Derived: these bytes were generated by this project's agents or exports. They are not independent "
    "external evidence for the claims they were generated from."
)

SCHEMA = """
CREATE TABLE IF NOT EXISTS imports (
    id TEXT PRIMARY KEY,
    source_id TEXT,
    kind TEXT NOT NULL,
    path TEXT NOT NULL,
    content_sha256 TEXT NOT NULL,
    executor TEXT NOT NULL,
    command TEXT,
    url TEXT,
    imported_at TEXT NOT NULL,
    provenance TEXT NOT NULL,
    assurance TEXT NOT NULL
);
"""


class Provenance(StrEnum):
    runtime_captured = "runtime_captured"
    host_reported = "host_reported"
    agent_authored = "agent_authored"
    derived = "derived"


class ImportRecord(Record):
    id: str
    source_id: str | None = None
    kind: str
    path: str
    content_sha256: str
    executor: str
    command: str | None = None
    url: str | None = None
    imported_at: str
    provenance: Literal["host_reported", "derived"]
    assurance: str


def ensure_schema(conn: sqlite3.Connection) -> None:
    with conn:
        conn.executescript(SCHEMA)


def _record(row: sqlite3.Row | tuple) -> ImportRecord:
    keys = ("id", "source_id", "kind", "path", "content_sha256", "executor", "command", "url",
            "imported_at", "provenance", "assurance")
    return ImportRecord(**dict(zip(keys, tuple(row), strict=True)))


_COLUMNS = "id, source_id, kind, path, content_sha256, executor, command, url, imported_at, provenance, assurance"


def get_import(conn: sqlite3.Connection, import_id: str) -> ImportRecord | None:
    try:
        row = conn.execute(f"SELECT {_COLUMNS} FROM imports WHERE id=?", (import_id,)).fetchone()
    except sqlite3.OperationalError:
        return None
    return _record(row) if row else None


def import_for_source(conn: sqlite3.Connection, source_id: str) -> ImportRecord | None:
    try:
        row = conn.execute(f"SELECT {_COLUMNS} FROM imports WHERE source_id=?", (source_id,)).fetchone()
    except sqlite3.OperationalError:  # table not created yet
        return None
    return _record(row) if row else None


def list_imports(conn: sqlite3.Connection) -> list[ImportRecord]:
    try:
        rows = conn.execute(f"SELECT {_COLUMNS} FROM imports ORDER BY rowid").fetchall()
    except sqlite3.OperationalError:
        return []
    return [_record(r) for r in rows]


def _blobs(store) -> BlobStore:
    return store if isinstance(store, BlobStore) else store.blobs


def _generated_by(
    conn: sqlite3.Connection, project_root: Path | None, content_sha256: str, path: Path | None
) -> str | None:
    """Name what generated these bytes in this project, or None."""
    try:
        row = conn.execute(
            "SELECT artifact_id, revision FROM artifacts WHERE content_sha256=? LIMIT 1", (content_sha256,)
        ).fetchone()
    except sqlite3.OperationalError:
        row = None
    if row:
        return f"artifact {row[0]} r{row[1]}"
    if project_root is not None and path is not None:
        try:
            if path.resolve().is_relative_to((project_root / "output").resolve()):
                return "the project's exported output"
        except OSError:
            pass
    return None


def reject_self_confirmation(
    conn: sqlite3.Connection, *, content_sha256: str, independent: bool = True,
    project_root: Path | None = None, path: Path | None = None,
) -> Provenance | None:
    """Generated material stays `derived`. Presenting it as independent external evidence is refused."""
    origin = _generated_by(conn, project_root, content_sha256, path)
    if origin is None:
        return None
    if independent:
        raise BrokerError(
            "SELF_CONFIRMATION_REJECTED",
            f"these bytes were generated by this project ({origin}); they are derived, not independent evidence",
            {"provenance": Provenance.derived.value, "origin": origin},
        )
    return Provenance.derived


def register_import(
    conn: sqlite3.Connection, broker_or_blobs, *, path: Path | str, kind: str, executor: str,
    command: str | None = None, url: str | None = None, claimed_independent: bool = False,
) -> ImportRecord:
    """Snapshot `path`. Given a Broker it also becomes a citable source `import-<n>`; a BlobStore only stores bytes."""
    ensure_schema(conn)
    source = Path(path)
    if not source.is_file():
        raise BrokerError("SOURCE_NOT_FOUND", f"import file {str(path)!r} does not exist")
    data = source.read_bytes()
    digest = sha256_bytes(data)
    blobs = _blobs(broker_or_blobs)
    derived = reject_self_confirmation(
        conn, content_sha256=digest, independent=claimed_independent,
        project_root=blobs.root.parents[1], path=source,
    )
    provenance = derived or Provenance.host_reported

    existing = conn.execute(
        f"SELECT {_COLUMNS} FROM imports WHERE content_sha256=? AND kind=? AND executor=? "
        "AND command IS ? AND url IS ?",
        (digest, kind, executor, command, url),
    ).fetchone()
    if existing:
        return _record(existing)

    blobs.put(data)
    record_id = f"import-{conn.execute('SELECT COUNT(*) FROM imports').fetchone()[0] + 1}"
    source_id = None
    if hasattr(broker_or_blobs, "register_source"):
        source_id = broker_or_blobs.register_source(record_id, source).source_id
    record = ImportRecord(
        id=record_id, source_id=source_id, kind=kind, path=str(source), content_sha256=digest,
        executor=executor, command=command, url=url, imported_at=datetime.now(UTC).isoformat(),
        provenance=provenance.value,
        assurance=DERIVED_ASSURANCE if provenance is Provenance.derived else HOST_ASSURANCE,
    )
    with conn:
        conn.execute(
            f"INSERT INTO imports ({_COLUMNS}) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
            tuple(record.model_dump().values()),
        )
    return record
